#!/usr/bin/env python3
"""Bundle the engine, one game's rules and its data into a single Global script.

Usage: python tools/bundle.py games/sample [-o build/Global.lua]

Modules are wrapped in a tiny require() so the output runs in TTS as-is:
  src/engine/<name>.lua  -> require("engine.<name>")
  <game>/<name>.lua      -> require("game.<name>")   (rules.lua -> game.rules)
  <game>/<name>.json     -> require("game.<name>")   (converted to a Lua table)
src/main.lua is appended last as the script body. Paste the result into the
Global script, or push it with the TTS Editor extension for VS Code.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PRELUDE = """\
-- Generated by tools/bundle.py from {game}. Do not edit; edit src/ and rebuild.
local __cz_modules, __cz_loaded = {{}}, {{}}
local function require(name)
  local loaded = __cz_loaded[name]
  if loaded == nil then
    local loader = __cz_modules[name]
    if not loader then error("module not found: " .. tostring(name), 2) end
    loaded = loader(name)
    if loaded == nil then loaded = true end
    __cz_loaded[name] = loaded
  end
  return loaded
end
"""


def lua_string(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    return f'"{out}"'


def to_lua(value, indent=0):
    pad = "  " * (indent + 1)
    if isinstance(value, dict):
        items = [f"{pad}[{lua_string(str(k))}] = {to_lua(v, indent + 1)}," for k, v in value.items() if v is not None]
        return "{\n" + "\n".join(items) + "\n" + "  " * indent + "}" if items else "{}"
    if isinstance(value, list):
        items = [f"{pad}{to_lua(v, indent + 1)}," for v in value]
        return "{\n" + "\n".join(items) + "\n" + "  " * indent + "}" if items else "{}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return lua_string(value)
    raise TypeError(f"can't convert {type(value).__name__} to Lua")


def collect(game):
    modules = {}
    for path in sorted((ROOT / "src" / "engine").glob("*.lua")):
        modules[f"engine.{path.stem}"] = path.read_text(encoding="utf-8")
    for path in sorted(game.glob("*.lua")):
        modules[f"game.{path.stem}"] = path.read_text(encoding="utf-8")
    for path in sorted(game.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        modules[f"game.{path.stem}"] = f"-- from {path.name}\nreturn {to_lua(data)}\n"
    for required in ("game.rules", "game.cards", "game.art"):
        if required not in modules:
            hint = {"game.cards": "run tools/csv2json.py", "game.art": "run tools/make_sheets.py"}.get(required, "")
            raise SystemExit(f"{game}: missing {required.split('.')[1]} ({hint})")
    return modules


def bundle(game):
    parts = [PRELUDE.format(game=game.relative_to(ROOT).as_posix() if game.is_relative_to(ROOT) else game)]
    for name, source in collect(game).items():
        parts.append(f"__cz_modules[{lua_string(name)}] = function(...)\n{source.rstrip()}\nend\n")
    parts.append("-- src/main.lua\n" + (ROOT / "src" / "main.lua").read_text(encoding="utf-8"))
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("game", type=Path)
    parser.add_argument("-o", "--output", type=Path, default=ROOT / "build" / "Global.lua")
    args = parser.parse_args()
    game = args.game.resolve()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(bundle(game), encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
